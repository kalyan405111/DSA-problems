#   1 1
#  1 2 1
# 1 3 3 1
#1 4 6 4 1
###################################################

n = 5
for i in range(n):
    print(" "*(n-i),end="")
    val = 1
    print(val, end=" ")
    for j in range(1, i + 1):
        val = val * (i - j + 1) // j
        print(val, end=" ")
    print()
